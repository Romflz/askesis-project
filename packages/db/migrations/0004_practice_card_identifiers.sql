-- Cards added from a practice deck ("Add to my decks") before identifiers existed get the
-- identifier that button now gives them: the deck's slug and the first 10 hex digits of
-- the SHA-256 of the front (practiceCardIdentifier in @askesis/core). Adding the deck
-- again then skips them instead of adding copies. The button tags each card with the
